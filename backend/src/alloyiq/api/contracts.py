"""Contract export (D110): docs/contracts/openapi.json and docs/contracts/events/*.schema.json.

Usage: python -m alloyiq.api.contracts <output_dir>      (scripts/gen-contracts.ps1)
       python -m alloyiq.api.contracts --check <dir>     (exit 1 if the files differ)

The OpenAPI document comes from the FastAPI app. Every boundary model is also added to
components.schemas, so the generated TypeScript types exist before a route ships.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from alloyiq.api.schemas import auth, billing, catalog, history, reports, research
from alloyiq.api.schemas.events import ACCOUNT_EVENTS, RUN_EVENTS, EventEnvelope


def _boundary_models() -> list[type[BaseModel]]:
    found: dict[str, type[BaseModel]] = {}
    for module in (auth, catalog, research, billing, reports, history):
        for obj in vars(module).values():
            if (
                isinstance(obj, type)
                and issubclass(obj, BaseModel)
                and obj.__module__ == module.__name__
                and not obj.__name__.startswith("_")
            ):
                found[obj.__name__] = obj
    return [found[k] for k in sorted(found)]


async def _ok() -> None:
    return None


def build_openapi() -> dict[str, Any]:
    from alloyiq.api.app import create_app
    from alloyiq.config import Settings

    app = create_app(Settings(app_env="test", deployment_version="contract"), readiness_probe=_ok)
    doc = app.openapi()
    _, defs = models_json_schema(
        [(m, "serialization") for m in _boundary_models()],
        ref_template="#/components/schemas/{model}",
    )
    schemas = doc.setdefault("components", {}).setdefault("schemas", {})
    for name, schema in sorted(defs.get("$defs", {}).items()):
        schemas.setdefault(name, schema)
    doc["components"]["schemas"] = dict(sorted(schemas.items()))
    return doc


def build_event_schemas() -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for scope, registry in (("run", RUN_EVENTS), ("account", ACCOUNT_EVENTS)):
        for event_type, model in registry.items():
            envelope = EventEnvelope.model_json_schema()
            payload = model.model_json_schema(mode="serialization")
            defs = {**envelope.pop("$defs", {}), **payload.pop("$defs", {})}
            envelope["properties"]["payload"] = payload
            envelope["title"] = f"{scope}:{event_type}"
            envelope["$schema"] = "https://json-schema.org/draft/2020-12/schema"
            envelope["x-sse-event"] = event_type
            envelope["x-scope"] = scope
            if defs:
                envelope["$defs"] = defs
            out[f"{scope}.{event_type}.schema.json"] = envelope
    return out


def _dump(obj: object) -> str:
    return json.dumps(obj, indent=2, sort_keys=False, ensure_ascii=False) + "\n"


def render(out_dir: Path) -> dict[Path, str]:
    files = {out_dir / "openapi.json": _dump(build_openapi())}
    for name, schema in build_event_schemas().items():
        files[out_dir / "events" / name] = _dump(schema)
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    out_dir = Path(args[0] if args else "../docs/contracts")
    files = render(out_dir)
    if check:
        stale = [
            p
            for p, text in files.items()
            if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        extra = sorted(set((out_dir / "events").glob("*.schema.json")) - set(files))
        for p in stale:
            print(f"out of date: {p}")
        for p in extra:
            print(f"not generated by code: {p}")
        return 1 if stale or extra else 0
    (out_dir / "events").mkdir(parents=True, exist_ok=True)
    for old in (out_dir / "events").glob("*.schema.json"):
        if old not in files:
            old.unlink()
    for path, text in files.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} contract files to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
